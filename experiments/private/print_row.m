function print_row(row)
    % print_row(row) — one console line for a summary row from summarise_runs
    labels = setdiff(fieldnames(row), {'n_runs', 'collision_rate', 'collision_rate_lo', ...
        'collision_rate_hi', 'min_distance_median', 'min_distance_min', 'min_distance_max', ...
        'reached_all_rate', 'reached_mean', 'infeasible_steps_mean'}, 'stable');
    txt = strjoin(cellfun(@(f) sprintf('%s=%s', f, num2str(row.(f))), labels, ...
                          'UniformOutput', false), '  ');
    fprintf('%-60s contact %.0f%% [%.0f, %.0f]  dmin med %.3f (min %.3f)  all reached %.0f%% (mean %.1f)  infeas %.1f\n', ...
            txt, 100*row.collision_rate, 100*row.collision_rate_lo, 100*row.collision_rate_hi, ...
            row.min_distance_median, row.min_distance_min, 100*row.reached_all_rate, row.reached_mean, ...
            row.infeasible_steps_mean);
end
